"""Fetch IRIS Lab Instagram posts (2020 onward) for the Lab News cards.

Writes js/ig-posts.js (const IG_POSTS = [...]) and saves each post image to
assets/news/ig_<id>.jpg, because Instagram image URLs expire after a few days.
Needs the IG_TOKEN environment variable (Instagram API with Instagram Login,
long-lived user access token of the @iris.unist professional account).
"""
import json, os, sys, urllib.parse, urllib.request

SINCE = "2020-01-01"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG_DIR = os.path.join(ROOT, "assets", "news")
OUT = os.path.join(ROOT, "js", "ig-posts.js")
FIELDS = "id,caption,media_type,media_url,thumbnail_url,permalink,timestamp,children{media_type,media_url,thumbnail_url}"


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "iris-lab-site-sync"}), timeout=60) as r:
        return r.read()


def main():
    token = os.environ.get("IG_TOKEN", "").strip()
    if not token:
        print("IG_TOKEN secret is not set; nothing to do.")
        return 0
    url = "https://graph.instagram.com/me/media?" + urllib.parse.urlencode({"fields": FIELDS, "limit": 50, "access_token": token})
    items = []
    while url:
        data = json.loads(get(url))
        if "error" in data:
            print("Instagram API error:", data["error"].get("message"))
            return 1
        page = data.get("data", [])
        items += page
        if page and page[-1].get("timestamp", "") < SINCE:
            break
        url = data.get("paging", {}).get("next")

    os.makedirs(IMG_DIR, exist_ok=True)
    posts = []
    for m in items:
        ts = m.get("timestamp", "")
        if ts[:10] < SINCE:
            continue
        src = m.get("thumbnail_url") if m.get("media_type") == "VIDEO" else m.get("media_url")
        if m.get("media_type") == "CAROUSEL_ALBUM":
            kids = (m.get("children") or {}).get("data") or []
            if kids:
                k = kids[0]
                src = k.get("thumbnail_url") if k.get("media_type") == "VIDEO" else k.get("media_url")
        rel = f"assets/news/ig_{m['id']}.jpg"
        path = os.path.join(ROOT, rel)
        if src and not os.path.exists(path):
            try:
                with open(path, "wb") as f:
                    f.write(get(src))
            except Exception as e:  # keep the post even if the image fails
                print("image failed", m["id"], e)
        posts.append({
            "src": "instagram",
            "url": m.get("permalink"),
            "date": ts[:10],
            "text": (m.get("caption") or "").strip(),
            **({"image": rel} if os.path.exists(path) else {}),
        })

    posts.sort(key=lambda p: p["date"], reverse=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by scripts/fetch_instagram.py. Do not edit by hand. */\n")
        f.write("const IG_POSTS = " + json.dumps(posts, ensure_ascii=False, indent=1) + ";\n")
    print(f"{len(posts)} Instagram posts written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
